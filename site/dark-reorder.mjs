import puppeteer from 'puppeteer-core'
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const b = await puppeteer.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: 'new' })
const p = await b.newPage()
await p.setViewport({ width: 1440, height: 900 })
await p.goto('http://localhost:4175/notes/物理/物理竞赛/力学/00-竞赛力学总览.html', { waitUntil: 'networkidle0' })
await sleep(4000)
const grab = () => p.evaluate(() =>
  [...document.querySelectorAll('.vp-doc .mermaid svg text')].map(t => t.textContent.trim()).filter(Boolean).slice(0, 10)
)
const before = await grab()
console.log('浅色文本:', before.length ? before.join(' | ') : '(空)')
const mCount = await p.evaluate(() => document.querySelectorAll('.vp-doc .mermaid').length)
console.log('mermaid 图数量:', mCount)
await p.evaluate(() => document.documentElement.classList.add('dark'))
await sleep(3000)
const after = await grab()
console.log('暗色文本:', after.length ? after.join(' | ') : '(空)')
console.log('顺序一致:', JSON.stringify(before) === JSON.stringify(after) ? '✓' : '✗')
await b.close()
